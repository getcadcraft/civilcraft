/**
 * Gerber X2 (RS-274X) and Excellon output, a Gerber reader for round trips, and the Gerber job file (0.8 XE.11). Written from the published Gerber
 * Layer Format Specification structure: %FSLAX46Y46*%, %MOMM*%, apertures C/R/O, G36/G37 regions, %LPD/LPC polarity, X2 attributes
 * (TF.FileFunction, FilePolarity, SameCoordinates, GenerationSoftware, CreationDate, ProjectId; TA.AperFunction; TO.N / TO.P / TO.C).
 * Copper pours are drawn the Gerber way: the region first, the other nets' copper cleared by the pour clearance with clear polarity, then every
 * object drawn dark again (solid connection, no thermal reliefs). Arcs are not written (pads and tracks are straight/flash). No text is written
 * on the legend layer (a stroke font is not built): the legend carries the footprints' silk lines and, optionally, courtyards.
 */
import { bbox } from './geom.js';
import { problem } from './board.js';

const SOFTWARE = '%TF.GenerationSoftware,CadCraft,lib-pcb,1.0*%';
const um = (v) => Math.round(v * 1e6);
const coord = (x, y) => 'X' + um(x) + 'Y' + um(y);
const f6 = (v) => (+v).toFixed(6).replace(/\.?0+$/, '') || '0';
function uuidFor(name) { // deterministic RFC-4122-shaped id from the name (FNV-1a, version-5 style bits); not a security id
  let h = [0x811c9dc5, 0x01000193, 0xcbf29ce4, 0x84222325]; const hex = []; for (let k = 0; k < 4; k++) { let x = h[0] ^ k; for (const c of name + k) { x ^= c.charCodeAt(0); x = Math.imul(x, 0x01000193) >>> 0; } hex.push(x.toString(16).padStart(8, '0')); }
  const s = hex.join(''); return s.slice(0, 8) + '-' + s.slice(8, 12) + '-5' + s.slice(13, 16) + '-a' + s.slice(17, 20) + '-' + s.slice(20, 32);
}
const layerFn = (board, name) => { const i = board.layers.indexOf(name), n = board.layers.length; return 'Copper,L' + (i + 1) + ',' + (i === 0 ? 'Top' : i === n - 1 ? 'Bot' : 'Inr'); };

class Writer {
  constructor(board, fileFunction, polarity, opts) {
    this.out = []; this.ap = new Map(); this.apList = []; this.board = board; this.cur = null; this.net = undefined; this.body = [];
    this.header = ['G04 ' + board.name + ', ' + fileFunction + ', generated by CadCraft lib-pcb*', '%TF.FileFunction,' + fileFunction + '*%', '%TF.FilePolarity,' + polarity + '*%', '%TF.SameCoordinates,' + uuidFor(board.name).slice(0, 8) + '*%', SOFTWARE, '%TF.CreationDate,' + (opts.date || '1970-01-01T00:00:00+00:00') + '*%', '%TF.ProjectId,' + board.name.replace(/[,*%]/g, '_') + ',' + uuidFor(board.name) + ',' + (opts.revision || 'A') + '*%', '%TF.Part,Single*%', '%FSLAX46Y46*%', '%MOMM*%'];
  }
  aperture(shape, w, h, fn) { // returns the D code, defining it once
    const key = shape + f6(w) + 'x' + f6(h || 0) + '|' + (fn || ''); let a = this.ap.get(key);
    if (!a) { a = { d: 10 + this.apList.length, def: '%ADD' + (10 + this.apList.length) + shape + ',' + f6(w) + (shape === 'C' ? '' : 'X' + f6(h)) + '*%', fn }; this.ap.set(key, a); this.apList.push(a); }
    return 'D' + a.d;
  }
  select(code) { if (this.cur !== code) { this.body.push(code + '*'); this.cur = code; } }
  setNet(net, ref, pad) { // object attributes
    const tag = net + '|' + (ref || '') + '|' + (pad || ''); if (this.net === tag) return; if (this.net !== undefined) this.body.push('%TD*%');
    this.net = tag; if (net) this.body.push('%TO.N,' + net + '*%'); else this.body.push('%TO.N,N/C*%'); if (ref) { this.body.push('%TO.P,' + ref + ',' + pad + '*%'); this.body.push('%TO.C,' + ref + '*%'); }
  }
  clearAttrs() { if (this.net !== undefined) { this.body.push('%TD*%'); this.net = undefined; } }
  flash(code, x, y) { this.select(code); this.body.push(coord(x, y) + 'D03*'); }
  draw(code, pts) { this.select(code); this.body.push(coord(pts[0][0], pts[0][1]) + 'D02*'); for (const p of pts.slice(1)) this.body.push(coord(p[0], p[1]) + 'D01*'); }
  region(poly) { this.body.push('G36*'); this.body.push(coord(poly[0][0], poly[0][1]) + 'D02*'); for (const p of poly.slice(1)) this.body.push(coord(p[0], p[1]) + 'D01*'); this.body.push(coord(poly[0][0], poly[0][1]) + 'D01*'); this.body.push('G37*'); }
  polarity(p) { this.body.push('%LP' + p + '*%'); }
  text() {
    const defs = []; for (const a of this.apList) { if (a.fn) defs.push('%TA.AperFunction,' + a.fn + '*%'); defs.push(a.def); if (a.fn) defs.push('%TD*%'); }
    return [...this.header, ...defs, 'G01*', 'G75*', '%LPD*%', ...this.body, 'M02*', ''].join('\n');
  }
}

/** Draw a pad (or its grown copy for mask/clear) with the right aperture or a region. grow in mm per side. */
function drawPad(W, pad, grow, fn, attrs = true) {
  const rot = ((Math.round(pad.rot) % 360) + 360) % 360, ortho = Math.abs(pad.rot - Math.round(pad.rot / 90) * 90) < 1e-9, sw = rot === 90 || rot === 270;
  if (attrs) W.setNet(pad.net, pad.ref, pad.num);
  if (pad.shape === 'circle') { W.flash(W.aperture('C', pad.w + 2 * grow, 0, fn), pad.x, pad.y); return; }
  if (ortho && (pad.shape === 'rect' || pad.shape === 'roundrect')) { const w = (sw ? pad.h : pad.w) + 2 * grow, h = (sw ? pad.w : pad.h) + 2 * grow; W.flash(W.aperture('R', w, h, fn), pad.x, pad.y); return; }
  if (ortho && pad.shape === 'oval') { const w = (sw ? pad.h : pad.w) + 2 * grow, h = (sw ? pad.w : pad.h) + 2 * grow; W.flash(W.aperture('O', w, h, fn), pad.x, pad.y); return; }
  const c = Math.cos(pad.rot * Math.PI / 180), s = Math.sin(pad.rot * Math.PI / 180), hw = pad.w / 2 + grow, hh = pad.h / 2 + grow;
  W.region([[-hw, -hh], [hw, -hh], [hw, hh], [-hw, hh]].map(([x, y]) => [pad.x + x * c - y * s, pad.y + x * s + y * c]));
}

/** Generate every file. Returns {files: {name: text}, job: object, problems}. opts: date (ISO string; default fixed so output is repeatable), revision, tentVias (true), silkCourtyard, pasteMargin. */
export function writeGerber(board, opts = {}) {
  const files = {}, problems = [], R = board.rules, tent = opts.tentVias !== false, nameBase = (opts.prefix || board.name).replace(/[^A-Za-z0-9_.-]/g, '_');
  const items = board.items(), layerFiles = [];
  const put = (suffix, W, fn, pol) => { const name = nameBase + '-' + suffix; files[name] = W.text(); layerFiles.push({ name, fn, pol }); };
  // copper
  board.layers.forEach((layer) => {
    const W = new Writer(board, layerFn(board, layer), 'Positive', opts), here = items.filter((i) => i.layers.includes(layer));
    const zs = here.filter((i) => i.kind === 'zone');
    for (const z of zs) {
      W.clearAttrs(); W.setNet(z.net); W.region(z.prim.pts); W.clearAttrs();
      W.polarity('C');
      for (const o of here) {
        if (o.kind === 'zone' || o.net === z.net && o.net) continue;
        if (o.kind === 'track') { W.draw(W.aperture('C', o.width + 2 * z.clearance), [o.prim.a, o.prim.b]); }
        else if (o.kind === 'via') W.flash(W.aperture('C', o.prim.r * 2 + 2 * z.clearance), o.prim.a[0], o.prim.a[1]);
        else if (o.kind === 'pad') drawPad(W, o.pad, z.clearance, undefined, false);
      }
      for (const h of board.drills()) if (h.kind === 'hole' && !h.plated) W.flash(W.aperture('C', h.drill + 2 * z.clearance), h.x, h.y);
      if (R.edgeClearance) W.draw(W.aperture('C', 2 * R.edgeClearance), [...board.outline, board.outline[0]]);
      W.polarity('D');
    }
    for (const o of here) {
      if (o.kind === 'zone') continue;
      if (o.kind === 'track') { W.setNet(o.net); W.draw(W.aperture('C', o.width, 0, 'Conductor'), [o.prim.a, o.prim.b]); }
      else if (o.kind === 'via') { W.setNet(o.net); W.flash(W.aperture('C', o.prim.r * 2, 0, 'ViaPad'), o.prim.a[0], o.prim.a[1]); }
      else drawPad(W, o.pad, 0, o.pad.drill > 0 ? 'ComponentPad' : 'SMDPad,CuDef');
    }
    W.clearAttrs(); put(layer.replace(/\./g, '_') + '.gbr', W, layerFn(board, layer), 'Positive');
  });
  // mask, paste, legend, profile on each side that has parts or copper
  for (const [side, copperLayer, tag] of [['Top', board.layers[0], 'F'], ['Bot', board.layers[board.layers.length - 1], 'B']]) {
    const padsHere = items.filter((i) => i.kind === 'pad' && i.layers.includes(copperLayer));
    const M = new Writer(board, 'Soldermask,' + side, 'Negative', opts);
    for (const o of padsHere) drawPad(M, o.pad, R.maskMargin, 'Material');
    if (!tent) for (const o of items) if (o.kind === 'via') M.flash(M.aperture('C', o.prim.r * 2 + 2 * R.maskMargin), o.prim.a[0], o.prim.a[1]);
    M.clearAttrs(); put(tag + '_Mask.gbr', M, 'Soldermask,' + side, 'Negative');
    const P = new Writer(board, 'Paste,' + side, 'Positive', opts);
    for (const o of padsHere) if (o.pad.smd) drawPad(P, o.pad, -(opts.pasteMargin || 0), 'SMDPad,CuDef');
    P.clearAttrs(); put(tag + '_Paste.gbr', P, 'Paste,' + side, 'Positive');
    const S = new Writer(board, 'Legend,' + side, 'Positive', opts), line = S.aperture('C', 0.12);
    for (const p of board.parts.filter((q) => (q.side === 'bottom') === (side === 'Bot'))) {
      const wp = (pt) => { const lx = p.side === 'bottom' ? -pt[0] : pt[0], c = Math.cos(p.rot * Math.PI / 180), s = Math.sin(p.rot * Math.PI / 180); return [p.x + lx * c - pt[1] * s, p.y + lx * s + pt[1] * c]; };
      for (const l of p.silk) if (l.length > 1) S.draw(line, l.map(wp));
      if (opts.silkCourtyard) S.draw(line, [...board.courtyardWorld(p), board.courtyardWorld(p)[0]]);
    }
    S.clearAttrs(); put(tag + '_Silkscreen.gbr', S, 'Legend,' + side, 'Positive');
  }
  const E = new Writer(board, 'Profile,NP', 'Positive', opts); E.draw(E.aperture('C', 0.1), [...board.outline, board.outline[0]]); put('Edge_Cuts.gbr', E, 'Profile,NP', 'Positive');
  // drills
  const d = writeDrill(board, opts); Object.assign(files, Object.fromEntries(Object.entries(d.files).map(([k, v]) => [nameBase + '-' + k, v])));
  const job = gerberJob(board, layerFiles.map((l) => ({ ...l, name: l.name })), d, opts, nameBase);
  files[nameBase + '-job.gbrjob'] = JSON.stringify(job, null, 2);
  if (!board.outline || board.outline.length < 3) problems.push(problem('gerber.outline', 'The board has no outline; Edge_Cuts is empty.'));
  return { files, job, problems };
}

/** Excellon drill files: plated (vias, plated pad holes) and non-plated. Decimal metric, absolute. */
export function writeDrill(board, opts = {}) {
  const hs = board.drills(), files = {}, counts = { plated: 0, nonplated: 0 };
  for (const plated of [true, false]) {
    const list = hs.filter((h) => h.plated === plated); if (!list.length) continue;
    const sizes = [...new Set(list.map((h) => +h.drill.toFixed(4)))].sort((a, b) => a - b), n = board.layers.length;
    const out = ['M48', '; DRILL file {CadCraft lib-pcb} date ' + (opts.date || '1970-01-01T00:00:00+00:00'), '; FORMAT={-:-/ absolute / metric / decimal}', '; #@! TF.FileFunction,' + (plated ? 'Plated,1,' + n + ',PTH' : 'NonPlated,1,' + n + ',NPTH'), '; #@! TF.FilePolarity,Positive', '; #@! TF.GenerationSoftware,CadCraft,lib-pcb,1.0', 'FMAT,2', 'METRIC'];
    sizes.forEach((s, i) => out.push('T' + (i + 1) + 'C' + s.toFixed(3)));
    out.push('%', 'G90', 'G05');
    sizes.forEach((s, i) => { out.push('T' + (i + 1)); for (const h of list.filter((q) => +q.drill.toFixed(4) === s)) out.push('X' + h.x.toFixed(4) + 'Y' + h.y.toFixed(4)); });
    out.push('M30', ''); files[plated ? 'PTH.drl' : 'NPTH.drl'] = out.join('\n'); counts[plated ? 'plated' : 'nonplated'] = list.length;
  }
  return { files, counts };
}

function gerberJob(board, layerFiles, drill, opts, nameBase) {
  const [x0, y0, x1, y1] = bbox(board.outline);
  return { Header: { GenerationSoftware: { Vendor: 'CadCraft', Application: 'lib-pcb', Version: '1.0' }, CreationDate: opts.date || '1970-01-01T00:00:00+00:00' },
    GeneralSpecs: { ProjectId: { Name: board.name, GUID: uuidFor(board.name), Revision: opts.revision || 'A' }, Size: { X: +(x1 - x0).toFixed(4), Y: +(y1 - y0).toFixed(4) }, LayerNumber: board.layers.length, BoardThickness: board.thickness },
    FilesAttributes: [...layerFiles.map((l) => ({ Path: l.name, FileFunction: l.fn, FilePolarity: l.pol })), ...Object.keys(drill.files).map((k) => ({ Path: nameBase + '-' + k, FileFunction: k.startsWith('PTH') ? 'Plated,1,' + board.layers.length + ',PTH' : 'NonPlated,1,' + board.layers.length + ',NPTH', FilePolarity: 'Positive' }))],
    MaterialStackup: board.layers.map((l, i) => ({ Type: 'Copper', Name: l, ...(i < board.layers.length - 1 ? {} : {}) })) };
}

