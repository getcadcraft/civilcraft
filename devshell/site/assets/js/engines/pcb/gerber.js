/** Read a Gerber file (the subset written above, plus common RS-274X: C/R/O apertures, regions, polarity, X2 attributes, straight draws). Arcs and macros are named, not drawn. */
export function readGerber(text) {
  const problems = [], res = { units: null, fs: null, apertures: {}, objects: [], fileAttrs: {}, bbox: null, problems, ended: false };
  const blocks = []; let i = 0;
  while (i < text.length) {
    const c = text[i];
    if (c === '%') { const j = text.indexOf('%', i + 1); if (j < 0) { problems.push(problem('gerber.read.unterminated', 'An extended command is not closed with %.')); break; } for (const b of text.slice(i + 1, j).split('*')) if (b.trim()) blocks.push({ ext: true, t: b.trim() }); i = j + 1; }
    else if (c === '\n' || c === '\r' || c === ' ') i++;
    else { const j = text.indexOf('*', i); if (j < 0) { problems.push(problem('gerber.read.unterminated', 'A command is not closed with *.')); break; } blocks.push({ ext: false, t: text.slice(i, j).trim() }); i = j + 1; }
  }
  let ap = null, x = 0, y = 0, pol = 'D', inRegion = false, region = null, attrs = {}, interp = 'G01', scale = 1e-6;
  const grow = (px, py, r) => { if (pol !== 'D') return; const b = res.bbox ||= [Infinity, Infinity, -Infinity, -Infinity]; b[0] = Math.min(b[0], px - r); b[1] = Math.min(b[1], py - r); b[2] = Math.max(b[2], px + r); b[3] = Math.max(b[3], py + r); };
  const half = (a) => (a ? Math.max(a.w, a.h || 0) / 2 : 0);
  for (const { ext, t } of blocks) {
    if (ext) {
      let m;
      if ((m = /^FSLAX(\d)(\d)Y(\d)(\d)$/.exec(t))) { res.fs = { int: +m[1], dec: +m[2] }; scale = Math.pow(10, -m[2]); }
      else if (/^FS/.test(t)) problems.push(problem('gerber.read.format', 'Unsupported coordinate format: ' + t + '.'));
      else if ((m = /^MO(MM|IN)$/.exec(t))) res.units = m[1];
      else if ((m = /^ADD(\d+)([A-Z]+[A-Za-z0-9_]*),?(.*)$/.exec(t))) { const p = m[3].split('X').map(Number); if (m[2] === 'C') res.apertures['D' + m[1]] = { shape: 'C', w: p[0], h: p[0], fn: attrs.AperFunction }; else if (m[2] === 'R' || m[2] === 'O') res.apertures['D' + m[1]] = { shape: m[2], w: p[0], h: p[1], fn: attrs.AperFunction }; else { res.apertures['D' + m[1]] = { shape: m[2], w: 0, h: 0, unsupported: true }; problems.push(problem('gerber.read.aperture', 'Aperture D' + m[1] + ' (' + m[2] + ') is a macro or polygon; not drawn.', { severity: 'warning' })); } }
      else if (/^AM/.test(t)) problems.push(problem('gerber.read.macro', 'An aperture macro was ignored.', { severity: 'warning' }));
      else if ((m = /^LP([DC])$/.exec(t))) pol = m[1];
      else if (/^L[MRS]/.test(t)) problems.push(problem('gerber.read.transform', 'Aperture transformation ' + t + ' is not applied.', { severity: 'warning' }));
      else if ((m = /^TF\.([A-Za-z]+),?(.*)$/.exec(t))) res.fileAttrs[m[1]] = m[2];
      else if ((m = /^TA\.([A-Za-z]+),?(.*)$/.exec(t))) attrs[m[1]] = m[2];
      else if ((m = /^TO\.([A-Za-z]+),?(.*)$/.exec(t))) attrs['O' + m[1]] = m[2];
      else if ((m = /^TD(?:\.(.+))?$/.exec(t))) { if (m[1]) { delete attrs[m[1]]; delete attrs['O' + m[1]]; } else attrs = {}; }
      continue;
    }
    if (/^G04/.test(t)) continue;
    if (t === 'M02') { res.ended = true; continue; }
    if (t === 'G36') { inRegion = true; region = []; continue; }
    if (t === 'G37') { if (region && region.length) { res.objects.push({ type: 'region', pts: region, polarity: pol, attrs: { ...attrs } }); for (const p of region) grow(p[0], p[1], 0); } inRegion = false; region = null; continue; }
    if (/^G0?[123]$/.test(t) || t === 'G74' || t === 'G75') { if (/^G0?[23]$/.test(t)) { interp = t; problems.push(problem('gerber.read.arc', 'Circular interpolation (' + t + ') is read but not drawn.', { severity: 'warning' })); } else if (/^G0?1$/.test(t)) interp = 'G01'; continue; }
    let m = /^(?:G0?1)?(?:X(-?\d+))?(?:Y(-?\d+))?(?:I(-?\d+))?(?:J(-?\d+))?(?:D0?([123]))?$/.exec(t);
    if (m && (m[1] !== undefined || m[2] !== undefined || m[5])) {
      const nx = m[1] !== undefined ? +m[1] * scale : x, ny = m[2] !== undefined ? +m[2] * scale : y, d = m[5];
      if (d === '2') { if (inRegion && region.length) { /* a region contour restarts */ } x = nx; y = ny; if (inRegion) region = region.length ? [...region] : []; if (inRegion) region.push([x, y]); continue; }
      if (d === '1') { if (inRegion) { region.push([nx, ny]); } else if (interp === 'G01') { const a = res.apertures[ap]; res.objects.push({ type: 'draw', a: [x, y], b: [nx, ny], aperture: ap, polarity: pol, width: a ? a.w : 0, attrs: { ...attrs } }); grow(x, y, half(a)); grow(nx, ny, half(a)); } x = nx; y = ny; continue; }
      if (d === '3') { const a = res.apertures[ap]; if (!a) problems.push(problem('gerber.read.no-aperture', 'A flash at ' + nx + ',' + ny + ' uses an aperture that is not defined.')); res.objects.push({ type: 'flash', at: [nx, ny], aperture: ap, shape: a?.shape, w: a?.w, h: a?.h, polarity: pol, attrs: { ...attrs } }); grow(nx, ny, half(a)); x = nx; y = ny; continue; }
      x = nx; y = ny; continue;
    }
    if ((m = /^D(\d+)$/.exec(t)) && +m[1] >= 10) { if (!res.apertures['D' + m[1]]) problems.push(problem('gerber.read.undefined-aperture', 'D' + m[1] + ' is selected but never defined.')); ap = 'D' + m[1]; continue; }
    problems.push(problem('gerber.read.unknown', 'Unknown command "' + t + '".', { severity: 'warning' }));
  }
  if (!res.ended) problems.push(problem('gerber.read.no-m02', 'The file does not end with M02*.'));
  if (!res.fs) problems.push(problem('gerber.read.no-format', 'No %FS...*% coordinate format.'));
  return res;
}

/** Read an Excellon drill file as written above (decimal metric): {tools: {T1: dia}, holes: [{x, y, dia}], attrs}. */
export function readDrill(text) {
  const tools = {}, holes = [], attrs = [], problems = []; let cur = null, body = false, metric = false;
  for (const raw of text.split(/\r?\n/)) {
    const l = raw.trim(); if (!l) continue;
    if (l.startsWith('; #@!')) { attrs.push(l.slice(5).trim()); continue; } if (l.startsWith(';')) continue;
    if (l === '%') { body = true; continue; } if (l === 'M48') continue; if (l === 'METRIC') { metric = true; continue; }
    let m; if (!body && (m = /^T(\d+)C([\d.]+)/.exec(l))) { tools['T' + m[1]] = +m[2]; continue; }
    if (body) { if ((m = /^T(\d+)$/.exec(l))) { cur = 'T' + m[1]; continue; } if ((m = /^X(-?[\d.]+)Y(-?[\d.]+)$/.exec(l))) { if (!cur || !tools[cur]) problems.push(problem('drill.read.no-tool', 'A hole before any tool.')); holes.push({ x: +m[1], y: +m[2], dia: tools[cur] }); continue; } if (l === 'M30') continue; }
  }
  if (!metric) problems.push(problem('drill.read.units', 'The drill file is not metric.', { severity: 'warning' }));
  return { tools, holes, attrs, problems };
}
