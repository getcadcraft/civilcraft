/** WCAG contrast of two #rrggbb colours (1 .. 21). */
export function contrastRatio(a, b) {
  const lum = (h) => { const v = [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16) / 255).map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4)); return 0.2126 * v[0] + 0.7152 * v[1] + 0.0722 * v[2]; };
  const x = lum(a), y = lum(b); return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05);
}
/** The two sheets an icon colour sits on (tokens.css --sheet, light and dark). */
export const ICON_SHEETS = { light: '#f3f6f8', dark: '#1d232b' };
/** Settings' contrast check: the picked colour against both sheets; ok = 3:1 or better on both (the bar for a graphic). */
export function iconColorCheck(hex) {
  if (typeof hex !== 'string' || !COLOR_RE.test(hex)) return null;
  const light = contrastRatio(hex, ICON_SHEETS.light), dark = contrastRatio(hex, ICON_SHEETS.dark);
  return { light: Math.round(light * 100) / 100, dark: Math.round(dark * 100) / 100, ok: light >= 3 && dark >= 3, fails: [light < 3 ? 'light' : '', dark < 3 ? 'dark' : ''].filter(Boolean) };
}

/** Puts the choice on <html> (data-cc-icons, --cc-icon-color, --cc-icon-theme, data-cc-icon-labels); app-settings.js calls the same on its side so a page paints right before the engine loads. */
export function applyIcons(root = document.documentElement) {
  root.setAttribute('data-cc-icons', iconStyle());
  const c = iconColor(); if (c) root.style.setProperty('--cc-icon-color', c); else root.style.removeProperty('--cc-icon-color');
  const t = iconThemeColor();
  if (t) root.style.setProperty('--cc-icon-theme', COLOR_RE.test(t) ? t : 'var(--layer-' + t + ')'); else root.style.removeProperty('--cc-icon-theme');
  if (iconLabelsFollow()) root.setAttribute('data-cc-icon-labels', '1'); else root.removeAttribute && root.removeAttribute('data-cc-icon-labels');
}
