export function iconKey(id, label = '') {
  const full = String(id || '').toLowerCase();
  if (BY_ID[full] && ICONS[BY_ID[full]]) return BY_ID[full];
  const key = full.split(/[.:]/).pop(), lab = String(label).toLowerCase().replace(/\s+/g, '');
  for (const [re, k] of RULES) if (ICONS[k] && (re.test(key) || re.test(lab))) return k;
  return null;
}

const NS = 'http://www.w3.org/2000/svg';
/** A fresh <svg class="ccic"> for a key (scales with its font size / --ic-size; the roles are coloured by app-workspace.css). */
export function iconNode(key) {
  const inner = ICONS[key]; if (!inner) return null;
  const s = document.createElementNS(NS, 'svg');
  s.setAttribute('viewBox', '0 0 32 32'); s.setAttribute('class', 'ccic'); s.setAttribute('aria-hidden', 'true'); s.setAttribute('focusable', 'false');
  s.innerHTML = inner;   // our own constants above, never page or user text
  return s;
}

export const STORE = 'cc-icons';
const STYLES = ['full', 'outline', 'app'];
const COLOR_RE = /^#[0-9a-fA-F]{6}$/;
function read() { try { const o = JSON.parse(localStorage.getItem(STORE) || '{}'); return o && typeof o === 'object' ? o : {}; } catch (e) { return {}; } }
export const iconStyle = () => { const s = read().style; return STYLES.includes(s) ? s : 'full'; };
export const iconColor = () => { const c = read().color; return typeof c === 'string' && COLOR_RE.test(c) ? c : ''; };
/** Puts the choice on <html> (data-cc-icons, --cc-icon-color); app-settings.js calls the same on its side so a page paints right before the engine loads. */
export function applyIcons(root = document.documentElement) {
  root.setAttribute('data-cc-icons', iconStyle());
  const c = iconColor(); if (c) root.style.setProperty('--cc-icon-color', c); else root.style.removeProperty('--cc-icon-color');
}
