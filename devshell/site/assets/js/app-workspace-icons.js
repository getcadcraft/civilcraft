/** Turn the Bootstrap glyphs already inside `root` (menus and chrome built as HTML) into set drawings where the table knows them; unknown ones are logged. */
export function wireGlyphs(root, block = '') {
  if (!root || !iconsWired()) return root;
  for (const i of root.querySelectorAll('i.bi')) {
    const bi = [...i.classList].find((c) => c.startsWith('bi-') && c !== 'bi'); if (!bi) continue;
    const k = BI_KEY[bi], n = k ? asSet(k) : null;
    if (n) i.replaceWith(n); else MISSING.set(block + '||' + bi, { block, id: '', label: '', bi });
  }
  return root;
}
/**
 * Markup an app wrote itself (a tool bar of `<i class="bi bi-zoom-in">` buttons) and that the engine moved into a block. The app may toggle the glyph's class later
 * (an eye that turns into a crossed eye), so the glyph is never replaced: it stays, hidden, and the set drawing sits in front of it and follows its class (one small
 * observer per glyph). Lab builds only, like everything here; style `app` and released apps never get it.
 */
const SHADOW = new WeakMap();
const glyphOf = (i) => [...i.classList].find((c) => c.startsWith('bi-') && c !== 'bi') || '';
function appKey(i, bi) {
  const t = ((i.closest('button,a,summary') || i).getAttribute?.('title') || '') + ' ' + ((i.closest('button,a,summary') || i).getAttribute?.('aria-label') || '');
  if (/arrow-(counter)?clockwise/.test(bi) && /turn|rotate/i.test(t)) return /counter/.test(bi) ? 'viewturnccw' : 'viewturncw';
  if (bi === 'bi-arrow-counterclockwise') return 'undo'; if (bi === 'bi-arrow-clockwise') return 'redo';
  return BI_KEY[bi] || null;
}
export function wireAppGlyphs(root, block = 'app') {
  if (!root || !iconsWired()) return 0;
  let n = 0;
  for (const i of root.querySelectorAll('i.bi:not([data-ccw])')) {
    if (i.closest('.ccic') || !i.parentNode) continue;
    i.setAttribute('data-ccw', '1');
    const draw = () => {
      const bi = glyphOf(i), k = bi ? appKey(i, bi) : null, old = SHADOW.get(i);
      if (old) old.remove();
      const node = k ? asSet(k) : null;
      if (!node) { SHADOW.delete(i); i.style.display = ''; if (bi) MISSING.set(block + '||' + bi, { block, id: '', label: '', bi }); return; }
      node.setAttribute('data-ccw-for', bi); i.parentNode.insertBefore(node, i); SHADOW.set(i, node); i.style.display = 'none'; n++;
    };
    draw();
    new MutationObserver(draw).observe(i, { attributes: true, attributeFilter: ['class'] });
  }
  return n;
}
/** Lab builds with a layout on: keep the app-written glyphs inside the layout's blocks wired (one debounced observer; nothing when wiring is off). */
let watching = false;
export function watchAppGlyphs() {
  if (watching || typeof document === 'undefined' || !document.body || !iconsWired()) return;
  watching = true; let t = 0;
  const pass = () => { t = 0; for (const b of document.querySelectorAll('main.ws-on [data-ws-blk]')) wireAppGlyphs(b, 'app'); };
  new MutationObserver(() => { if (!t) t = setTimeout(pass, 250); }).observe(document.body, { childList: true, subtree: true });
  pass();
}
