/**
 * sections.js — the canonical structural steel section table (0.5 MQ.3). DOM-free, imports nothing: Node, workers and pages
 * load it as it is. The one copy that is edited is lib/shapes/sections.js; `node tools/shapes/sync.mjs` copies it byte for
 * byte into each app that uses it (detailcraft/dev/shapes/, cadcraft/dev/shapes/) and `--check` fails when a copy differs.
 *
 * Every size is copied from a published table, never estimated, and bin/test-shapes.mjs cross-checks every row: the area
 * worked out from the dimensions against the published area, and the published weight against that area × steel density,
 * so a mistyped digit fails. Dimensions are facts; only the numbers are taken, never a document's layout or text.
 *
 *   AISC — "AISC Shapes Database v16.0" (American Institute of Steel Construction, 2023; the Excel file published with the
 *          16th edition Steel Construction Manual, https://www.aisc.org/publications/steel-construction-manual-resources/),
 *          US units, rows in the database's own order, smallest first:
 *          W, S:  d, bf, tw, tf, kdes (in), A (in²), nominal weight W (lb/ft). W is drawn with root fillet r = kdes − tf (the
 *                 database gives no radius); S (sloped flanges) is drawn with parallel flanges of the average thickness tf
 *                 and square corners.
 *          C:     d, bf, tw, tf (average flange thickness), A, W. Drawn like S: parallel flanges, square corners.
 *          L:     equal legs: b, t, A, W; unequal legs: long leg, short leg, t, A, W. Square corners (no fillet or toe radii).
 *          HSS rectangular and square: H, B, nominal t, design t (= 0.93 × nominal, AISC 360-22 §B4.2), A, W. Corners drawn
 *                 with outer radius 2 × design t, as AISC computes the section properties.
 *          HSS round: OD (from the name: the database rounds it to three figures), nominal t, design t, A, W.
 *          Pipe:  OD, nominal t, design t, A, W (Pipe…STD, …XS, …XXS), listed by OD, then wall.
 *          Three rows keep the value DetailCraft carried before this table existed, so models made with it do not change:
 *          W10X49 d = 9.98 (the database rounds it to 10.0), HSS4.500X0.237 W = 10.79 (database 10.8), HSS6.625X0.280
 *          W = 18.97 (database 18.99).
 *   EN   — EN 10365:2017 "Hot rolled steel channels, I and H sections — Dimensions and masses":
 *          IPE 80–600, HEA and HEB 100–1000: h, b, tw, tf, r (mm), A (cm²), mass G (kg/m). A is the standard's formula
 *          value from the nominal dimensions (root radii included) and G = A × 7850 kg/m³, to the standard's precision.
 *          UPN 50–400 (sloped flanges): h, b, tw, tf, r1, r2 (mm), A (cm²), G (kg/m). Drawn with parallel flanges of
 *          thickness tf and square corners.
 *
 * A record (sectionRows(), findSection(name)) is a frozen plain object in millimetres:
 *   { name, family, kind, source, …dimensions, areaPub (mm²), massPub (kg/m), pub: {units, …the row as published} }
 *   kind I: d, bf, tw, tf, r · C: d, bf, tw, tf, r (0) · L: b (the leg along u), t, h (the leg along v; only when the legs
 *   differ) · RHS: h, b, t (design), tNom, ro, ri · CHS: D, t (design), tNom.
 * Names are the tables' own (W12X26, HSS4X4X1/4, Pipe4STD, IPE300); displayName() prints AISC names with a lowercase x
 * between numbers (W12x26), as the AISC Manual does. Lookups ignore case.
 *
 * Geometry (the same code DetailCraft draws with): sections live in the (u, v) plane, v up (the depth), u across, centred on
 * their bounding box. outline(p, seg) → loops [[u, v]…] (first outer CCW, then holes CW); exactArea(p) (mm², arcs exact);
 * bbox(loop), shoelace(loop), loopLength(loop).
 */

