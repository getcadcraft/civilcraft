export function say(t, key, vars = {}, locale = 'en') {
  let v = typeof t === 'function' ? t(key, vars) : key;
  if (v === key || v == null) v = (/^es-MX$/i.test(locale) ? ES_MX[key] : undefined) ?? EN[key] ?? key;
  return String(v).replace(/\{(\w+)\}/g, (_, k) => (vars[k] === undefined ? '{' + k + '}' : String(vars[k])));
}
