if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const LANG = path.join(path.dirname(fileURLToPath(import.meta.url)), '../../public_html/assets/apps/partcraft/dev/lang/');
  const check = process.argv.includes('--check');
  let off = 0;
  for (const [file, words] of [['en.json', EN], ['es-MX.json', ES]]) {
    const p = path.join(LANG, file), cur = JSON.parse(fs.readFileSync(p, 'utf8'));
    if (Object.entries(words).every(([k, v]) => cur[k] === v)) { console.log(file + ': in step (' + Object.keys(words).length + ' words)'); continue; }
    off++;
    if (check) { console.log(file + ': out of step'); continue; }
    fs.writeFileSync(p, JSON.stringify({ ...cur, ...words }, null, 2) + '\n');
    console.log(file + ': wrote ' + Object.keys(words).length + ' words');
  }
  if (check && off) process.exit(1);
}
