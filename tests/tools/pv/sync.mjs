/**
 * sync.mjs — the solar PV engine in more than one app (0.8 EG.15, round 3 session `civil_PART_3`; rule 39: copies are made, never edited). BimCraft's
 * `pv*.js` files (session energy_PART_2) are canonical; a target app carries byte-identical copies of the DOM-free core in its `pv/` folder:
 *
 *   pv.js          modules, planes, fitting, row spacing         pv-sun.js     sun, clear sky, plane-of-array light
 *   pv-yield.js    the year's energy                              pv-shade.js   rays against triangles (shadows)
 *   pv-string.js   string sizing                                  render/sun.js the sun's position (NOAA)
 *
 * `pv-sun.js` imports `clearSky`, `climateFor` and `GSC` from BimCraft's `daylight-bim-sky.js`, which pulls in the IFC readers. The target gets a file of
 * the same name that holds ONLY those three declarations, cut out of the original by this script (so it cannot drift); it is marked as generated.
 *
 *   node tools/pv/sync.mjs --to civilcraft       copy where it differs, print what changed
 *   node tools/pv/sync.mjs --check --to civilcraft    compare only; exit 1 on any drift
 *
 * `--to` is required (rule 31). PV_APPS_DIR overrides the apps folder (the test).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const APPS = process.env.PV_APPS_DIR || path.join(ROOT, 'public_html/assets/apps');
const SRC = path.join(APPS, 'bimcraft/dev');
export const TARGETS = ['civilcraft'];
export const ENGINE = ['pv.js', 'pv-sun.js', 'pv-yield.js', 'pv-shade.js', 'pv-string.js', 'render/sun.js'];

/** The sky shim: CLIMATES, GSC, clearSky and climateFor cut from daylight-bim-sky.js. */
export function skyShim() {
  const s = fs.readFileSync(path.join(SRC, 'daylight-bim-sky.js'), 'utf8');
  const a = s.indexOf('export const CLIMATES'), b = s.indexOf('/** The site\'s latitude, longitude, height and north from IfcSite');
  const c = s.indexOf('/** The climate factors that fit the date');
  if (a < 0 || b < 0 || c < 0) throw new Error('daylight-bim-sky.js changed shape: the sky declarations were not found');
  const climateFor = s.slice(c).split('\n').filter((l, i) => i < 2 || l.startsWith('export const climateFor')).join('\n').split('\n').slice(0, 2).join('\n');
  return '/* SPDX-License-Identifier: Apache-2.0 */\n/* i18n-ignore-file — generated by tools/pv/sync.mjs from bimcraft/dev/daylight-bim-sky.js (the clear-sky declarations only); do not edit. */\n'
    + '/** The Hottel clear sky and the climate factors pv-sun.js reads, without the IFC readers the rest of the original file imports. */\n'
    + s.slice(a, b).trimEnd() + '\n' + climateFor.trimEnd() + '\n';
}

/** What differs in the named apps: [{ app, file, to, bytes }]. */
export function drift(apps) {
  const out = [];
  for (const app of apps) {
    const dir = path.join(APPS, app, 'dev/pv');
    const want = new Map(ENGINE.map((f) => [f, fs.readFileSync(path.join(SRC, f))]));
    want.set('daylight-bim-sky.js', Buffer.from(skyShim()));
    for (const [f, bytes] of want) {
      const to = path.join(dir, f);
      if (!fs.existsSync(to) || !fs.readFileSync(to).equals(bytes)) out.push({ app, file: f, to, bytes });
    }
  }
  return out;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const i = process.argv.indexOf('--to'), apps = i > 0 ? String(process.argv[i + 1] || '').split(',').filter(Boolean) : [];
  const check = process.argv.includes('--check');
  if (!apps.length || apps.some((a) => !TARGETS.includes(a))) { console.error('usage: node tools/pv/sync.mjs [--check] --to ' + TARGETS.join(',') + '  (--to is required)'); process.exit(2); }
  const d = drift(apps);
  for (const x of d) {
    console.log((check ? 'differs  ' : 'copy     ') + x.app + '/' + x.file);
    if (!check) { fs.mkdirSync(path.dirname(x.to), { recursive: true }); fs.writeFileSync(x.to, x.bytes); }
  }
  if (!d.length) console.log('in sync: ' + apps.join(', '));
  process.exit(check && d.length ? 1 : 0);
}
