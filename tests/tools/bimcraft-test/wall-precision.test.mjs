  const wall=readWalls(m.w())[0];
  m.change(saveWallDimension({level:level.guid,view:'plan:'+level.guid,axis:'y',offset:200,refs:[{wall:wall.guid,reference:'exterior',station:0.25},{wall:wall.guid,reference:'coreExterior',station:0.25}]}));
