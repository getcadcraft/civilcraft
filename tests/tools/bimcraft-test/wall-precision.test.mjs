test('custom types, core anchors, hosted openings, persistent dimensions, undo and IFC round trip',async()=>{
  const m=await model(),level=readLevels(m.w())[0];
  m.change(saveWallAssembly(recipe));
  m.change(saveWallAssembly({...recipe,key:'wall-interior',name:'SDH interior',exterior:false,layers:[{mat:'gypsum',t:12.7,function:'finish',core:false},{mat:'studs',t:88.9,function:'structure',core:true},{mat:'gypsum',t:12.7,function:'finish',core:false}]}));
  assert.equal(readAssemblies(m.w()).length,2);
  m.change(drawWalls({storey:level.guid,typeKey:recipe.key,segs:[{a:[0,0],b:[6000,0],justification:'coreCenter'},{a:[0,4000],b:[6000,4000],justification:'coreCenter'}],height:2700}));
  let walls=readWalls(m.w()),first=walls[0],second=walls[1];
  const anchor=locationLine(first).a[1];
  m.change(placeOpening({wall:first.guid,typeKey:'win-fixed',offset:2000,width:900,height:1200,sill:900}));
  const opening=readOpenings(m.w())[0];assert.ok(opening);
  for(const reference of WALL_REFERENCES)m.change(saveWallDimension({level:level.guid,view:'plan:'+level.guid,axis:'y',offset:1000,refs:[{wall:first.guid,reference,station:0.5},{wall:second.guid,reference,station:0.5}]}));
  const dims=readWallDimensions(m.w());assert.equal(dims.length,6);
  for(const d of dims)near(resolveDimension(d,readWalls(m.w())).value,4000);
  const beforePoint=referencePoint({wall:first.guid,reference:'coreExterior',station:0.5},walls);
  const oldBytes=m.ed.save();
  m.change(saveWallAssembly({...recipe,layers:recipe.layers.map((l,i)=>i===0?{...l,t:50.8}:l)}));
  walls=readWalls(m.w());near(walls[0].t,215.9);near(locationLine(walls[0]).a[1],anchor);
  near(referencePoint({wall:first.guid,reference:'coreExterior',station:0.5},walls)[1],beforePoint[1]);
  assert.equal(readOpenings(m.w())[0].guid,opening.guid);
  m.ed.undo();near(readWalls(m.w())[0].t,184.15);m.ed.redo();near(readWalls(m.w())[0].t,215.9);
  m.change(changeWall(second.guid,{a:[0,4500],b:[6000,4500]}));
  const dimension=readWallDimensions(m.w()).find(d=>d.refs[0].reference==='coreExterior');
  const expected=resolveDimension(dimension,readWalls(m.w())).value;
  near(expected, 4484.125);
  const reopened=await model(m.ed.save());
  assert.equal(readAssemblies(reopened.w()).length,2);assert.equal(readWallDimensions(reopened.w()).length,6);
  near(resolveDimension(readWallDimensions(reopened.w()).find(d=>d.guid===dimension.guid),readWalls(reopened.w())).value,expected);
  const isolated=await model(oldBytes);near(wallType(recipe.key,isolated.w()).layers[0].t,19.05);
  near(wallType(recipe.key,reopened.w()).layers[0].t,50.8);
  m.change(removeElements({walls:[first.guid]}));
  assert.equal(resolveDimension(readWallDimensions(m.w())[0],readWalls(m.w())).status,'missing');
  assert.equal(m.w().api.GetLine(m.w().mid,readWallDimensions(m.w())[0].id,false).Representation,null);
  m.ed.undo();assert.equal(resolveDimension(readWallDimensions(m.w())[0],readWalls(m.w())).status,'ok');
});
