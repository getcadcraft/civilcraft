/**
 * `node tools/bimcraft-test/elec-sync.mjs [--check]` (0.5 part 4 RC.6; session bim-residential): BimCraft's electrical
 * plan symbols ARE the CadCraft Electrical add-on's installation symbols. This reads them from the add-on
 * (`cadcraft/dev/addons/electrical/lib/install.js`, `INSTALL`) and writes `bimcraft/dev/res-elec-symbols.js` — data only,
 * generated, never edited by hand. `--check` fails when the file is not what the add-on gives now. Run it after the add-on's
 * symbols change.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const SRC = path.join(ROOT, 'public_html/assets/apps/cadcraft/dev/addons/electrical/lib/install.js');
const OUT = path.join(ROOT, 'public_html/assets/apps/bimcraft/dev/res-elec-symbols.js');

const { INSTALL, INSTALL_GROUPS } = await import(pathToFileURL(SRC).href);
const num = (v) => Math.round(v * 1e6) / 1e6;
const clean = (e) => {
  const o = {};
  for (const [k, v] of Object.entries(e)) {
    if (k === 'layer' || k === 'color') continue;
    o[k] = typeof v === 'number' ? num(v) : Array.isArray(v) ? JSON.parse(JSON.stringify(v), (kk, x) => (typeof x === 'number' ? num(x) : x)) : v;
  }
  return o;
};
const list = INSTALL.map((s) => ({ key: s.key, group: s.group, load: s.load, role: s.role || 'install', ents: s.draw().map(clean) }));
const text = `/* SPDX-License-Identifier: Apache-2.0 */
/**
 * res-elec-symbols.js — GENERATED by tools/bimcraft-test/elec-sync.mjs from the CadCraft Electrical add-on's installation
 * symbols (cadcraft/dev/addons/electrical/lib/install.js INSTALL): the same drawings in both apps. Do not edit; run the sync.
 * Each symbol: key, group, load (W, a planning default), role (install | board), ents (6 mm across at paper size; base point on
 * the wall, +y into the room; line {x1 y1 x2 y2}, circle {cx cy r}, arc {cx cy r a0 a1 (radians)}, poly {pts [{x y b}], closed},
 * hatch {solid, loops [[x, y, …]]}, text {x y h s}).
 */
export const GROUPS = ${JSON.stringify(INSTALL_GROUPS)};
export const SYMBOLS = [
${list.map((s) => '  ' + JSON.stringify(s)).join(',\n')},
];
`;
if (process.argv.includes('--check')) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (have !== text) { console.error('res-elec-symbols.js is not what the Electrical add-on gives now: run node tools/bimcraft-test/elec-sync.mjs'); process.exit(1); }
  console.log('res-elec-symbols.js matches the Electrical add-on (' + list.length + ' symbols)');
} else {
  fs.writeFileSync(OUT, text);
  console.log('wrote ' + path.relative(ROOT, OUT) + ' (' + list.length + ' symbols)');
}
